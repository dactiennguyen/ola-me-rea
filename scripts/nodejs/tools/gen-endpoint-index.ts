// Regenerates src/endpoints/index.ts from the endpoint files: every
// `export const <name> = define...(` becomes part of the registry.
// Files starting with "_" hold shared helpers and are skipped.
//
//   yarn gen:index          write the file
//   yarn gen:index --check  exit 1 if it is out of date (test/registry.test.ts checks the same)

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const DIR = new URL('../src/endpoints/', import.meta.url);
const INDEX = new URL('index.ts', DIR);
const EXPORT = /^export const (\w+) = define\w*\(/gm;

export function renderIndex(): string {
  const imports: string[] = [];
  const names: string[] = [];
  const files = readdirSync(DIR).filter(f => f.endsWith('.ts') && f !== 'index.ts' && !f.startsWith('_')).sort();
  for (const file of files) {
    const found = [...readFileSync(new URL(file, DIR), 'utf8').matchAll(EXPORT)].map(m => m[1]!);
    if (!found.length) throw new Error(`${file}: no "export const <name> = define...(" found.`);
    imports.push(`import { ${found.join(', ')} } from './${file}';`);
    names.push(...found);
  }
  return [
    '// Generated by tools/gen-endpoint-index.ts; run `yarn gen:index` after adding an endpoint.',
    '',
    ...imports,
    '',
    'export {',
    ...names.map(name => `  ${name},`),
    '};',
    '',
    'export const endpoints = {',
    ...names.map(name => `  ${name},`),
    '} as const;',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const next = renderIndex();
  if (process.argv.includes('--check')) {
    if (readFileSync(INDEX, 'utf8').replace(/\r\n/g, '\n') !== next) {
      console.error('src/endpoints/index.ts is out of date; run `yarn gen:index`.');
      process.exitCode = 1;
    }
  } else {
    writeFileSync(INDEX, next);
  }
}
